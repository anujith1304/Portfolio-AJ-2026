/**
 * Sets the site gate's password.
 *
 *   node scripts/set-password.mjs "your new password"
 *
 * Writes a fresh random salt and the SHA-256 of salt+password into
 * src/lib/gate.ts. The plaintext is never stored.
 *
 * Be clear-eyed about what that buys: the salt defeats precomputed tables, but
 * the hash ships inside a public repo and the keyspace is whatever you choose.
 * A six-digit number falls to brute force in well under a second. Treat this
 * as a curtain, and never reuse a password that protects anything real.
 */
import { randomBytes, createHash } from "node:crypto";
import { writeFileSync } from "node:fs";

const password = process.argv[2];
if (!password) {
  console.error('usage: node scripts/set-password.mjs "your new password"');
  process.exit(1);
}

const salt = randomBytes(16).toString("hex");
const hash = createHash("sha256").update(salt + password).digest("hex");

writeFileSync(
  "src/lib/gate.ts",
  `/**
 * The site gate's stored credential. Generated by scripts/set-password.mjs —
 * edit that, not this.
 *
 * This is a curtain, not a lock. The check runs in the browser after every
 * file has already been served, so the page source, the bundled JS and every
 * asset URL remain reachable without ever meeting it. These values sit in a
 * public repo; a short or numeric password is recoverable from them in under
 * a second. Never reuse a password that protects anything else.
 */
export const GATE_SALT = ${JSON.stringify(salt)};
export const GATE_HASH = ${JSON.stringify(hash)};

/** localStorage key holding the unlocked flag, per browser. */
export const GATE_KEY = "aj-gate";
`,
);

console.log(`gate password set (salt ${salt.slice(0, 8)}…, hash ${hash.slice(0, 12)}…)`);
